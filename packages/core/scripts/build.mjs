#!/usr/bin/env node
/*
 * Builds @multi-stores/core into dist/ (committed, so the apps and the
 * production server never build this package):
 *   dist/esm    ES modules ("import" condition: Next/Turbopack, vitest)
 *   dist/cjs    CommonJS   ("require" condition: Nest build, jest, api runtime)
 *   dist/types  declarations for both
 * It first regenerates src/designer/renderer-hash.ts (RENDERER_SHA256 = sha256
 * of design-renderer.ts with LF line endings).
 *
 *   node scripts/build.mjs                 # build into ./dist
 *   node scripts/build.mjs --out <dir>     # build into <dir> (used by check.mjs)
 *
 * TypeScript is resolved from multi-stores-shared/node_modules (or any
 * node_modules up the tree).
 */
import { execFileSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import { mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

export const pkgRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const require = createRequire(join(pkgRoot, 'package.json'));

export const lf = (s) => s.replace(/\r\n/g, '\n');
export const sha256 = (s) => createHash('sha256').update(lf(s), 'utf8').digest('hex');

const RENDERER = join(pkgRoot, 'src/designer/design-renderer.ts');
export const HASH_FILE = join(pkgRoot, 'src/designer/renderer-hash.ts');

/** Source text of renderer-hash.ts for the current renderer source. */
export function rendererHashModule() {
  const hash = sha256(readFileSync(RENDERER, 'utf8'));
  return (
    '// GENERATED by packages/core/scripts/build.mjs — do not edit.\n' +
    '// sha256 of design-renderer.ts (LF line endings): identifies the renderer\n' +
    '// source this build was made from; checked by scripts/check.mjs and the\n' +
    '// api/web renderer package specs. Separate module so the renderer stays import-free.\n' +
    'export const RENDERER_SHA256 =\n' +
    `  '${hash}';\n`
  );
}

function tsc(args) {
  const tscBin = require.resolve('typescript/bin/tsc');
  execFileSync(process.execPath, [tscBin, '-p', join(pkgRoot, 'tsconfig.json'), ...args], {
    stdio: 'inherit',
    cwd: pkgRoot,
  });
}

/**
 * Builds the package into `outDir` (absolute). `writeHash: false` compiles
 * the committed renderer-hash.ts as is (check mode).
 */
export function build(outDir, { writeHash = true } = {}) {
  if (writeHash) writeFileSync(HASH_FILE, rendererHashModule());
  rmSync(outDir, { recursive: true, force: true });
  const common = ['--noEmit', 'false'];
  tsc([...common, '--module', 'es2022', '--outDir', join(outDir, 'esm'),
    '--declaration', '--declarationDir', join(outDir, 'types')]);
  tsc([...common, '--module', 'commonjs', '--outDir', join(outDir, 'cjs')]);
  // Format markers so Node treats each folder correctly regardless of the
  // package root (which has no "type").
  mkdirSync(join(outDir, 'esm'), { recursive: true });
  writeFileSync(join(outDir, 'esm/package.json'), '{ "type": "module" }\n');
  writeFileSync(join(outDir, 'cjs/package.json'), '{ "type": "commonjs" }\n');
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const i = process.argv.indexOf('--out');
  const out = i > 0 ? resolve(process.argv[i + 1]) : join(pkgRoot, 'dist');
  build(out);
  console.log(`built @multi-stores/core into ${out}`);
}
