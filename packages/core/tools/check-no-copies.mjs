#!/usr/bin/env node
/*
 * Mirror guard (M5.3): fails when an app repo carries a copy of a
 * @multi-stores/core module instead of importing the package.
 *
 *   node <core>/tools/check-no-copies.mjs <repoRoot> [<repoRoot> ...]
 *
 * Scans src/, test/, scripts/ and prisma/ of each repo (.ts/.tsx/.js/.mjs/
 * .cjs/.json, skipping node_modules, .next and dist) and reports a file when
 *   - it contains the full body of a package source file or fixture
 *     (line endings normalized, so header-prefixed copies are caught too), or
 *   - it shares at least LINE_THRESHOLD distinct long source lines with the
 *     package (catches partial or outdated copies), or
 *   - it carries one of the old mirror markers (MIRROR headers, BEGIN MIRROR
 *     blocks, files generated by the removed sync scripts).
 * Exit code 1 on any finding. Also usable as a module: findCopies(roots).
 */
import { existsSync, readdirSync, readFileSync, statSync } from 'node:fs';
import { dirname, join, relative, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const pkgRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const lf = (s) => s.replace(/\r\n/g, '\n');

const SCAN_DIRS = ['src', 'test', 'scripts', 'prisma'];
const SKIP_DIRS = new Set(['node_modules', '.next', 'dist', 'coverage', '.git', '.turbo']);
const EXTS = /\.(ts|tsx|js|mjs|cjs|json)$/;
const MARKERS = [
  /MIRROR \(M4/,
  /BEGIN MIRROR/,
  /GENERATED by multi-stores-shared\/scripts\/sync-/,
];
// A file sharing this many distinct long (>= MIN_LINE chars, trimmed) lines
// with the package sources is treated as a (partial) copy.
const LINE_THRESHOLD = 25;
const MIN_LINE = 40;
// Barrels and generated stubs are too small to identify a copy.
const SKIP_SOURCES = new Set(['index.ts', 'renderer-hash.ts']);

function walk(dir, out) {
  for (const name of readdirSync(dir)) {
    if (SKIP_DIRS.has(name)) continue;
    const p = join(dir, name);
    const st = statSync(p);
    if (st.isDirectory()) walk(p, out);
    else if (EXTS.test(name)) out.push(p);
  }
  return out;
}

function packageSources() {
  const files = [
    ...walk(join(pkgRoot, 'src'), []).filter((f) => !SKIP_SOURCES.has(f.split(/[\\/]/).pop())),
    ...walk(join(pkgRoot, 'fixtures'), []),
  ];
  return files.map((f) => ({ name: relative(pkgRoot, f).replace(/\\/g, '/'), body: lf(readFileSync(f, 'utf8')).trim() }));
}

const longLines = (text) =>
  new Set(text.split('\n').map((l) => l.trim()).filter((l) => l.length >= MIN_LINE));

/** Returns `[{ file, reason }]` for every copy found under the given repo roots. */
export function findCopies(roots) {
  const sources = packageSources();
  const sourceLines = new Set();
  for (const s of sources) if (s.name.endsWith('.ts')) for (const l of longLines(s.body)) sourceLines.add(l);
  const findings = [];
  for (const root of roots) {
    for (const d of SCAN_DIRS) {
      const dir = join(root, d);
      if (!existsSync(dir)) continue;
      for (const file of walk(dir, [])) {
        const text = lf(readFileSync(file, 'utf8'));
        const marker = MARKERS.find((m) => m.test(text));
        if (marker) findings.push({ file, reason: `mirror marker ${marker}` });
        let copied = false;
        for (const s of sources) {
          if (text.includes(s.body)) {
            copied = true;
            findings.push({ file, reason: `copy of @multi-stores/core ${s.name}` });
          }
        }
        if (!copied && /\.(ts|tsx|js|mjs|cjs)$/.test(file)) {
          let shared = 0;
          for (const l of longLines(text)) if (sourceLines.has(l)) shared++;
          if (shared >= LINE_THRESHOLD) {
            findings.push({ file, reason: `shares ${shared} source lines with @multi-stores/core (partial copy)` });
          }
        }
      }
    }
  }
  return findings;
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const roots = process.argv.slice(2).map((r) => resolve(r));
  if (roots.length === 0) {
    console.error('usage: check-no-copies.mjs <repoRoot> [...]');
    process.exit(2);
  }
  const findings = findCopies(roots);
  if (findings.length > 0) {
    console.error('Copies of @multi-stores/core modules found (import the package instead, see multi-stores-shared/docs/SHARED-PACKAGE.md):');
    for (const f of findings) console.error(`  - ${f.file}: ${f.reason}`);
    process.exit(1);
  }
  console.log(`No copies of @multi-stores/core modules in ${roots.length} repo(s).`);
}
