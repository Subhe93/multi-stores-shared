#!/usr/bin/env node
/*
 * Copies the M4.1 personalization evaluator (types, conditions, evaluator,
 * display + personalization-cases.json) from shared to its api and web
 * mirrors (contract C12, same pattern as M4.0 rules.ts):
 *   - api: `src/common/personalization/`, each .ts file with a 3-line mirror header;
 *   - web: `src/lib/personalization/`, byte copies, sha256 pinned in evaluator.hash.ts.
 * The dashboard copies display.ts alone (WP-E, `src/lib/personalization.ts`).
 *
 *   node multi-stores-shared/scripts/sync-personalization-evaluator.mjs          # sync
 *   node multi-stores-shared/scripts/sync-personalization-evaluator.mjs --check  # verify only (exit 1 on drift)
 *
 * Hashes are computed with CRLF normalized to LF (git autocrlf on Windows).
 * rules.ts and personalization.vectors.json (M4.0) are not touched.
 */
import { createHash } from 'node:crypto';
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const sharedRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const monoRoot = resolve(sharedRoot, '..');
const SOURCE_DIR = join(sharedRoot, 'src/personalization');
const TS_FILES = ['types.ts', 'conditions.ts', 'evaluator.ts', 'display.ts'];
const JSON_FILES = ['personalization-cases.json'];
const API_DIR = join(monoRoot, 'multi-stores-api/src/common/personalization');
const WEB_DIR = join(monoRoot, 'multi-stores-web/src/lib/personalization');

const lf = (s) => s.replace(/\r\n/g, '\n');
const sha256 = (s) => createHash('sha256').update(lf(s), 'utf8').digest('hex');

function apiHeader(file) {
  return (
    '/* eslint-disable */\n' +
    `// MIRROR (M4.1 C12): below this 3-line header, a byte copy of multi-stores-shared/src/personalization/${file}.\n` +
    '// Never edit here: edit the shared file and run multi-stores-shared/scripts/sync-personalization-evaluator.mjs.\n'
  );
}

function hashModule(hashes) {
  const lines = Object.entries(hashes).map(([f, h]) => `  '${f}': '${h}',`);
  return (
    '// GENERATED by multi-stores-shared/scripts/sync-personalization-evaluator.mjs — do not edit.\n' +
    '// sha256 (LF line endings) of the M4.1 evaluator byte copies in this folder,\n' +
    '// checked by evaluator.spec.ts (contract C12).\n' +
    'export const EVALUATOR_MIRROR_SHA256: Record<string, string> = {\n' +
    lines.join('\n') +
    '\n};\n'
  );
}

const check = process.argv.includes('--check');
const drift = [];
const hashes = {};

function expectFile(path, content) {
  const current = existsSync(path) ? lf(readFileSync(path, 'utf8')) : null;
  if (current === content) return;
  if (check) drift.push(path);
  else writeFileSync(path, content, 'utf8');
}

for (const file of [...TS_FILES, ...JSON_FILES]) {
  const source = lf(readFileSync(join(SOURCE_DIR, file), 'utf8'));
  hashes[file] = sha256(source);
  const isTs = file.endsWith('.ts');
  expectFile(join(API_DIR, file), isTs ? apiHeader(file) + source : source);
  expectFile(join(WEB_DIR, file), source);
}
expectFile(join(WEB_DIR, 'evaluator.hash.ts'), hashModule(hashes));

if (check) {
  if (drift.length > 0) {
    console.error('Personalization evaluator mirrors out of sync:\n  ' + drift.join('\n  '));
    process.exit(1);
  }
  console.log('Personalization evaluator mirrors in sync.');
} else {
  console.log('Synced personalization evaluator mirrors:');
  for (const [f, h] of Object.entries(hashes)) console.log(`  ${f}  ${h}`);
}
