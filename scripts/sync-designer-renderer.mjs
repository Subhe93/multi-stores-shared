#!/usr/bin/env node
/*
 * Copies the designer renderer (M4.2 D2) from shared to its three mirrors and
 * rewrites each repo's RENDERER_SHA256 constant.
 *
 *   node multi-stores-shared/scripts/sync-designer-renderer.mjs          # sync
 *   node multi-stores-shared/scripts/sync-designer-renderer.mjs --check  # verify only (exit 1 on drift)
 *
 * The hash is computed over the file with CRLF normalized to LF, so a git
 * checkout with core.autocrlf does not break the mirror specs.
 */
import { createHash } from 'node:crypto';
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const sharedRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const monoRoot = resolve(sharedRoot, '..');
const SOURCE = join(sharedRoot, 'src/designer/design-renderer.ts');

const MIRRORS = [
  { repo: 'multi-stores-api', dir: 'src/modules/designer/render' },
  { repo: 'multi-stores-web', dir: 'src/lib/designer' },
  { repo: 'multi-stores-dashboard', dir: 'src/lib/designer' },
];

const lf = (s) => s.replace(/\r\n/g, '\n');
const sha256 = (s) => createHash('sha256').update(lf(s), 'utf8').digest('hex');

function hashModule(hash) {
  return (
    '// GENERATED by multi-stores-shared/scripts/sync-designer-renderer.mjs — do not edit.\n' +
    '// sha256 of design-renderer.ts (LF line endings), checked by the mirror spec.\n' +
    'export const RENDERER_SHA256 =\n' +
    `  '${hash}';\n`
  );
}

const check = process.argv.includes('--check');
const source = lf(readFileSync(SOURCE, 'utf8'));
const hash = sha256(source);
let drift = 0;

for (const m of MIRRORS) {
  const repoDir = join(monoRoot, m.repo);
  if (!existsSync(repoDir)) {
    console.warn(`skip ${m.repo} (not found)`);
    continue;
  }
  const dir = join(repoDir, m.dir);
  const file = join(dir, 'design-renderer.ts');
  const hashFile = join(dir, 'designer-renderer.hash.ts');
  if (check) {
    const okFile = existsSync(file) && sha256(readFileSync(file, 'utf8')) === hash;
    const okHash = existsSync(hashFile) && lf(readFileSync(hashFile, 'utf8')).includes(`'${hash}'`);
    if (!okFile || !okHash) {
      drift++;
      console.error(`DRIFT ${m.repo}/${m.dir} (file ${okFile ? 'ok' : 'differs'}, hash ${okHash ? 'ok' : 'differs'})`);
    } else console.log(`ok    ${m.repo}/${m.dir}`);
    continue;
  }
  mkdirSync(dir, { recursive: true });
  writeFileSync(file, source);
  writeFileSync(hashFile, hashModule(hash));
  console.log(`wrote ${m.repo}/${m.dir}`);
}

console.log(`RENDERER_SHA256 ${hash}`);
if (check && drift) process.exit(1);
